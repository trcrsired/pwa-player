/*
 * gen_iptv_cpp.js — turn the IPTV channel data source into a C++ inline
 * constexpr table that is compiled into pwaplayer.wasm.
 *
 * Usage:
 *   node build/gen_iptv_cpp.js <project_root>
 *
 * Input : cpp/iptvchannels.js   (plain data module, never shipped to the browser)
 * Output: cpp/iptv_channels_data.inc
 *
 * Every string is emitted as a sized ::fast_io::u8string_view (pointer + length),
 * so the C++ side never needs a NUL terminator scan.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const root = process.argv[2] || path.join(__dirname, "..");
const inputPath = path.join(root, "cpp", "iptvchannels.js");
const outputPath = path.join(root, "cpp", "iptv_channels_data.inc");

function loadChannels(file) {
    const source = fs.readFileSync(file, "utf8");
    const body = source
        .replace(/^\s*\/\/[^\n]*\n/, "")
        .replace(/export\s+const\s+iptvChannels\s*=/, "return ");
    // The data file is plain object/array literals, evaluating it is safe and
    // avoids hand writing a parser that would silently drift from the syntax.
    return new Function(body)();
}

// Escape a JS string so it can live inside a u8"..." literal. Non-ASCII UTF-8
// bytes are emitted verbatim (source and execution charsets are both UTF-8),
// hence the Buffer result: going through a JS string would re-encode them.
function toULiteral(s) {
    const out = [];
    for (const byte of Buffer.from(s, "utf8")) {
        switch (byte) {
            case 0x22: out.push(Buffer.from('\\"')); break;   // "
            case 0x5c: out.push(Buffer.from("\\\\")); break;  // backslash
            case 0x0a: out.push(Buffer.from("\\n")); break;
            case 0x0d: out.push(Buffer.from("\\r")); break;
            case 0x09: out.push(Buffer.from("\\t")); break;
            case 0x3f: out.push(Buffer.from("\\?")); break;   // avoid trigraph surprises
            default:
                if (byte < 0x20) {
                    out.push(Buffer.from("\\x" + byte.toString(16).padStart(2, "0")));
                } else {
                    out.push(Buffer.from([byte]));
                }
        }
    }
    return Buffer.concat(out);
}

// Lines are collected as raw byte chunks so UTF-8 survives untouched.
function line(...parts) {
    return Buffer.concat([...parts.map((p) => (Buffer.isBuffer(p) ? p : Buffer.from(p, "utf8"))), Buffer.from("\n")]);
}

const FLAG_NSFW = 1;
const FLAG_CORS = 2;
const NO_ZHCN = 0xffff;

function main() {
    const channels = loadChannels(inputPath);

    const allUrls = [];
    const zhcnNames = [];
    const zhcnIndex = new Map();

    const rows = channels.map((ch) => {
        const urls = ch.url ? [ch.url] : (ch.urls || []);
        if (urls.length === 0) {
            throw new Error(`channel "${ch.name}" has no url`);
        }
        if (urls.length > 0xffff) {
            throw new Error(`channel "${ch.name}" has too many urls`);
        }
        const first = allUrls.length;
        if (first > 0xffff) {
            throw new Error("more than 65535 urls: url_first would not fit in 16 bits");
        }
        for (const u of urls) {
            allUrls.push(u);
        }

        const localized = ch.nameLocalized && ch.nameLocalized.zhcn;
        let zhcn = NO_ZHCN;
        if (localized) {
            if (!zhcnIndex.has(localized)) {
                zhcnIndex.set(localized, zhcnNames.length);
                zhcnNames.push(localized);
            }
            zhcn = zhcnIndex.get(localized);
        }

        let flags = 0;
        if (ch.nsfw) flags |= FLAG_NSFW;
        if (ch.cors) flags |= FLAG_CORS;

        return { name: ch.name, first, count: urls.length, flags, zhcn };
    });

    const lines = [];
    lines.push(line("// Generated by build/gen_iptv_cpp.js — DO NOT EDIT."));
    lines.push(line("// Source: cpp/iptvchannels.js"));
    lines.push(line(`// channels: ${rows.length}, urls: ${allUrls.length}, zhcn names: ${zhcnNames.length}`));
    lines.push(line(""));
    lines.push(line("namespace iptv_data"));
    lines.push(line("{"));
    lines.push(line("// Bit flags stored per channel"));
    lines.push(line(`inline constexpr ::std::uint_least16_t flag_nsfw{${FLAG_NSFW}};`));
    lines.push(line(`inline constexpr ::std::uint_least16_t flag_cors{${FLAG_CORS}};`));
    lines.push(line(`inline constexpr ::std::uint_least16_t no_zhcn{${NO_ZHCN}};`));
    lines.push(line(""));
    lines.push(line("// All URLs, flat. A channel owns [url_first, url_first + url_count)."));
    lines.push(line(`inline constexpr ::fast_io::array<::fast_io::u8string_view, ${allUrls.length}> urls{{`));
    allUrls.forEach((u) => lines.push(line("\tu8\"", toULiteral(u), "\",")));
    lines.push(line("}};"));
    lines.push(line(""));
    lines.push(line("// Simplified Chinese display names (index referred to by channels)."));
    lines.push(line(`inline constexpr ::fast_io::array<::fast_io::u8string_view, ${zhcnNames.length}> zhcn_names{{`));
    zhcnNames.forEach((n) => lines.push(line("\tu8\"", toULiteral(n), "\",")));
    lines.push(line("}};"));
    lines.push(line(""));
    lines.push(line("// The channel table itself. Every name is a sized u8string_view."));
    lines.push(line(`inline constexpr ::fast_io::array<iptv_channel, ${rows.length}> channels{{`));
    rows.forEach((r) => {
        const zhcn = r.zhcn === NO_ZHCN ? "no_zhcn" : String(r.zhcn);
        lines.push(line(`\t{u8\"`, toULiteral(r.name),
            `\", ${r.first}, ${r.count}, ${r.flags}, ${zhcn}},`));
    });
    lines.push(line("}};"));
    lines.push(line(""));
    lines.push(line(`inline constexpr ::std::size_t channel_count{${rows.length}};`));
    lines.push(line("} // namespace iptv_data"));
    lines.push(line(""));

    fs.writeFileSync(outputPath, Buffer.concat(lines));

    const bytes = allUrls.reduce((a, u) => a + Buffer.byteLength(u), 0) +
        zhcnNames.reduce((a, n) => a + Buffer.byteLength(n), 0) +
        rows.reduce((a, r) => a + Buffer.byteLength(r.name), 0);
    console.log(`IPTV table: ${rows.length} channels, ${allUrls.length} urls, ` +
        `${zhcnNames.length} zhcn names, ${bytes} bytes of strings`);
    console.log("WROTE:", outputPath);
}

main();
